package cli

// Generated-file templates for `pal ci init`. @AGENT@ etc. are substituted
// after validation (ci_cmd.go validate); they contain no hostnames on purpose:
// the API address always comes from the repo's own PAL_API_URL variable.

const ciWorkflowTmpl = `# Generated by 'pal ci init' (ADR 0053). Re-run with --force to regenerate;
# 'pal ci init --check' fails if this file was edited by hand.
#
# Required repo configuration:
#   secret   PAL_API_KEY          key for a STAGING workspace (never production)
#   variable PAL_API_URL          control-plane base URL
#   variable PAL_CI_STAGING_ACK   set to 1 to confirm the key is not production
#   variable PAL_CLI_VERSION      pinned pal release tag to install, e.g. v0.21.0 (required)
name: pal-agent-ci

on:
  pull_request:
  push:
    branches: [@BRANCH@]

permissions:
  contents: read
  pull-requests: write

concurrency:
  group: pal-agent-ci-${{ github.ref }}
  cancel-in-progress: true

jobs:
  gate:
    runs-on: ubuntu-latest
    timeout-minutes: 20
    env:
      PAL_API_URL: ${{ vars.PAL_API_URL }}
      PAL_API_KEY: ${{ secrets.PAL_API_KEY }}
      PAL_CI_STAGING_ACK: ${{ vars.PAL_CI_STAGING_ACK }}
      PAL_CLI_VERSION: ${{ vars.PAL_CLI_VERSION }}
      PAL_CI_BASELINE_BRANCH: ${{ github.base_ref || github.ref_name }}
      PAL_CI_SET_BASELINE: ${{ github.event_name == 'push' && '1' || '' }}
    steps:
      - uses: actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1
      - uses: sigstore/cosign-installer@7e8b541eb2e61bf99390e1afd4be13a184e9ebc5 # v3.10.1
      - name: Run agent gates
        run: .pal/ci.sh
      - name: Job summary
        if: always()
        run: '[ -f pal-ci-summary.md ] && cat pal-ci-summary.md >> "$GITHUB_STEP_SUMMARY" || true'
      - name: Upload report
        if: always()
        uses: actions/upload-artifact@ea165f8d65b6e75b540449e92b4886f43607fa02 # v4.6.2
        with:
          name: pal-ci-report
          path: |
            pal-ci-report.json
            pal-ci-summary.md
          if-no-files-found: ignore
      - name: PR comment
        if: always() && github.event_name == 'pull_request' && github.event.pull_request.head.repo.full_name == github.repository
        continue-on-error: true
        uses: actions/github-script@60a0d83039c74a4aee543508d2ffcb1c3799cdea # v7.0.1
        with:
          script: |
            const fs = require('fs');
            if (!fs.existsSync('pal-ci-summary.md')) return;
            const body = fs.readFileSync('pal-ci-summary.md', 'utf8');
            const marker = '<!-- pal-ci-report -->';
            const { owner, repo } = context.repo;
            const issue_number = context.issue.number;
            const comments = await github.paginate(github.rest.issues.listComments, { owner, repo, issue_number });
            const mine = comments.find(c => c.body && c.body.includes(marker));
            if (mine) await github.rest.issues.updateComment({ owner, repo, comment_id: mine.id, body });
            else await github.rest.issues.createComment({ owner, repo, issue_number, body });
`

const ciScriptTmpl = `#!/usr/bin/env sh
# Generated by 'pal ci init' (ADR 0053). Works in any CI: export PAL_API_URL,
# PAL_API_KEY (staging workspace), PAL_CI_STAGING_ACK=1 and PAL_CLI_VERSION
# (an explicit release tag such as v0.21.0; there is no "latest"), then run this.
# Exit 0 only if every gate passed. Writes pal-ci-report.json and pal-ci-summary.md.
#
# The CLI comes from the signed GitHub release (ADR 0044): the binary's sha256 is
# checked against SHA256SUMS, and SHA256SUMS against its cosign bundle when cosign
# is installed. Any mismatch aborts. Escape hatch: PAL_CLI_PATH=/path/to/pal uses a
# prebuilt binary and skips the download.
set -eu

: "${PAL_API_URL:?set PAL_API_URL to your control-plane base URL}"
: "${PAL_API_KEY:?set PAL_API_KEY to a staging-workspace key}"

if [ -n "${PAL_CLI_PATH:-}" ]; then
  [ -x "$PAL_CLI_PATH" ] || { echo "PAL_CLI_PATH is not an executable file" >&2; exit 2; }
  pal_bin="$PAL_CLI_PATH"
else
  : "${PAL_CLI_VERSION:?set PAL_CLI_VERSION to a pinned pal release tag, e.g. v0.21.0}"
  case "$PAL_CLI_VERSION" in
    v[0-9]*.[0-9]*.[0-9]*) ;;
    *) echo "PAL_CLI_VERSION must be an explicit tag like v0.21.0" >&2; exit 2 ;;
  esac
  case "$(uname -s)" in Linux) os=linux ;; Darwin) os=darwin ;; *) echo "unsupported OS" >&2; exit 2 ;; esac
  case "$(uname -m)" in x86_64|amd64) arch=amd64 ;; arm64|aarch64) arch=arm64 ;; *) echo "unsupported CPU" >&2; exit 2 ;; esac
  repo="${PAL_CLI_REPO:-dshakes/pal}"
  base="https://github.com/$repo/releases/download/$PAL_CLI_VERSION"
  asset="pal_${os}_${arch}"
  dl="$(mktemp -d)"
  curl -fsSL --proto '=https' -o "$dl/$asset" "$base/$asset"
  curl -fsSL --proto '=https' -o "$dl/SHA256SUMS" "$base/SHA256SUMS"
  if command -v cosign >/dev/null 2>&1; then
    curl -fsSL --proto '=https' -o "$dl/SHA256SUMS.sigstore.json" "$base/SHA256SUMS.sigstore.json"
    cosign verify-blob --bundle "$dl/SHA256SUMS.sigstore.json" \
      --certificate-identity-regexp "^https://github\.com/$repo/\.github/workflows/release\.yml@refs/(heads|tags)/.+$" \
      --certificate-oidc-issuer https://token.actions.githubusercontent.com "$dl/SHA256SUMS" >/dev/null
  else
    echo "warning: cosign not found; verifying the checksum only" >&2
  fi
  want="$(awk -v a="$asset" '$2 == a { print $1 }' "$dl/SHA256SUMS")"
  [ -n "$want" ] || { echo "no checksum for $asset in SHA256SUMS" >&2; exit 2; }
  if command -v sha256sum >/dev/null 2>&1; then got="$(sha256sum "$dl/$asset" | awk '{ print $1 }')"; else got="$(shasum -a 256 "$dl/$asset" | awk '{ print $1 }')"; fi
  [ "$got" = "$want" ] || { echo "checksum mismatch for $asset" >&2; exit 2; }
  chmod +x "$dl/$asset"
  mkdir -p "${RUNNER_TEMP:-${TMPDIR:-/tmp}}/pal-cli"
  pal_bin="${RUNNER_TEMP:-${TMPDIR:-/tmp}}/pal-cli/pal"
  cp "$dl/$asset" "$pal_bin"
  rm -rf "$dl"
fi

branch="${PAL_CI_BASELINE_BRANCH:-@BRANCH@}"
if [ -n "${PAL_CI_SET_BASELINE:-}" ]; then
  exec "$pal_bin" ci check --agent "@AGENT@" --suite "@SUITE@" --manifest "@MANIFEST@" --branch "$branch" --stage --set-baseline
fi
exec "$pal_bin" ci check --agent "@AGENT@" --suite "@SUITE@" --manifest "@MANIFEST@" --branch "$branch" --stage
`
